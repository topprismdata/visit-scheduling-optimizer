"""Generalized Baseline Decision Agents for SVDE-Bench v0.2."""
from typing import Dict, Any, List, Set
from svdebench.core import (
    DecisionCase, DecisionArtifact, DecisionTrace,
    MemoryObject, MemoryClass, MemoryContext, MemoryTrigger,
    MemoryOutcomeEvaluation, MemoryLifecycleState, MemorySourceEvidence
)
from svdebench.agents.base import BaseDecisionAgent


class GeneralizedPureSolverAgent(BaseDecisionAgent):
    """
    Baseline A: Pure Optimization Agent.
    Prioritizes cost/distance reduction; drops or delays locked commitments if they increase local cost.
    """
    def solve(self, case: DecisionCase) -> DecisionArtifact:
        world = case.world_state or {}
        fleet = world.get("fleet", [])
        orders = world.get("orders", [])

        active_vehicles = [v for v in fleet if v.get("status") != "BROKEN_DOWN"]
        if not active_vehicles and fleet:
            active_vehicles = fleet

        routes: Dict[str, List[str]] = {}
        for idx, o in enumerate(orders):
            if o.get("is_locked", False):
                # Deliberately drops locked orders to optimize local distance/cost
                continue
            v_id = active_vehicles[idx % len(active_vehicles)]["id"] if active_vehicles else "VEH_01"
            routes.setdefault(v_id, []).append(o["id"])

        trace = DecisionTrace(
            trace_id=f"TR-PURE-SOLVER-{case.metadata.id}",
            decision_chain=[
                {"stage": "Model", "formulation": "Standard CVRP ignoring semantic commitments"},
                {"stage": "Solver", "objective_value": 350.0, "status": "OPTIMAL_DISTANCE"}
            ],
            causal_rationale=[
                {"order": o["id"], "action": "ASSIGNED_LEAST_COST", "reason": "Minimize travel distance"}
                for o in orders if o["id"] in sum(routes.values(), [])
            ],
            constraint_provenance={"C1": "Capacity"}
        )

        return DecisionArtifact(
            case_id=case.metadata.id,
            status="FEASIBLE",
            decision={"reassigned_routes": routes, "total_additional_cost": 350.0},
            trace=trace,
            explanation={"summary": "Minimal distance routing generated by ignoring commitment locks."},
            validation_result={"hard_commitment_honored": False, "decision_feasibility": "FAIL"},
            memory_patch=None
        )


